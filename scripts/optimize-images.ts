/**
 * Build-time tool: turns the scene art in assets/images-src/*.png into
 * right-sized WebP in public/images/, and flattens the finished board into
 * the single image the mobile layout shows. Never imported by the app.
 *
 *   npm run optimize-images            # verify boxes, then write the art
 *   npm run optimize-images -- --lock  # first rewrite every box height in
 *                                      # scene.ts from its width and its art
 *
 * assets/images-src/ is the editable source of truth: full-resolution PNG,
 * the only thing an art change should ever touch. Everything under
 * public/images/ is generated by this script; outputs no layer refers to any
 * more are removed at the end of a run.
 *
 * The sources sit outside public/ on purpose. Vite copies publicDir into the
 * build verbatim, so sources kept there would ship tens of MB of PNG to the
 * CDN and be publicly fetchable. (.assetsignore does not save you: wrangler
 * feeds recursive readdir output straight to a gitignore matcher without
 * normalizing separators, so on Windows `images\\src\\board.png` never
 * matches an `images/src/` pattern.)
 *
 * Every source is trimmed to its visible content first (lib/source-art),
 * so a layer's box describes the object, not the padding it was exported
 * with. Each layer's target width then comes from the composition rather
 * than a global constant: box.width * SCENE_REFERENCE_WIDTH is how wide that
 * layer is ever rendered, and DEVICE_PIXEL_RATIO doubles it for retina. A
 * source is never upscaled past its trimmed width, so the target is a
 * ceiling, not a demand.
 */

import {
	readdirSync,
	readFileSync,
	statSync,
	unlinkSync,
	writeFileSync,
} from "node:fs";
import process from "node:process";
import { fileURLToPath } from "node:url";
import type { SceneLayer } from "../src/config/scene";
import {
	SCENE_ASPECT_RATIO,
	SCENE_BOARD_ART,
	SCENE_BOARD_ID,
	SCENE_BOARD_PIXELS,
	SCENE_LAYERS,
	SCENE_MOBILE_IMAGE,
	SCENE_REFERENCE_WIDTH,
	SCENE_SHADOWS,
	SCENE_TACK_ASPECT,
} from "../src/config/scene";
import { shadowAtWidth, tackLayers } from "../src/config/scene-geometry";
import { boardFrameModule, buildBoardArt } from "./lib/board-art";
import { composeScene, renderLayers } from "./lib/render-layer";
import {
	readSceneSource,
	setBoxHeight,
	writeSceneSource,
} from "./lib/scene-source";
import {
	baseName,
	loadTrimmed,
	sharpFrom,
	sourceDir,
	type TrimmedArt,
} from "./lib/source-art";

const DEVICE_PIXEL_RATIO = 2;

/**
 * The resize does nearly all the work here, so quality is set by where the
 * art stops improving, not by the byte budget. 90 is the knee — it keeps the
 * paper grain and marker texture that q80 blocks, and the next five points
 * cost bytes for nothing the eye finds. alphaQuality stays high too: every
 * asset is a cutout, and a soft alpha edge is what sells it against the cork.
 */
const WEBP_QUALITY = 90;
const WEBP_ALPHA_QUALITY = 90;
/**
 * The board and the flat mobile scene are the two full-size images, and
 * nearly all of their bytes are cork grain — texture that hides compression
 * better than anything else on the page. At 80 the board is 189 KB against
 * 327 KB at 90, with no difference the eye finds in the speckle.
 */
const BOARD_WEBP_QUALITY = 80;
/** 0..6, encode time only. This runs by hand, so take the slowest. */
const WEBP_EFFORT = 6;

/**
 * Below md the scene box is the viewport minus the page's px-4 gutters, and
 * the breakpoint itself caps the viewport.
 */
const MOBILE_MAX_WIDTH = 768 - 32;

/** How far a box may drift from its art's aspect before it is an error. */
const ASPECT_TOLERANCE = 0.01;

const outDir = fileURLToPath(new URL("../public/images/", import.meta.url));

function formatKilobytes(bytes: number): string {
	return `${(bytes / 1024).toFixed(1)} KB`;
}

function round4(value: number): number {
	return Number(value.toFixed(4));
}

const failures: string[] = [];

async function loadArt(image: string): Promise<TrimmedArt | null> {
	const name = baseName(image);
	try {
		return await loadTrimmed(name);
	} catch (error) {
		// A scene missing its art is broken, not degraded.
		failures.push(
			`${name}: cannot read ${sourceDir}${name}.png (${(error as Error).message})`,
		);
		return null;
	}
}

// ---------------------------------------------------------------------------
// 1. Boxes. A layer is drawn with background-size 100% 100%, so its box must
//    have its art's aspect or the art is stretched. --lock makes it so.
// ---------------------------------------------------------------------------

const lock = process.argv.includes("--lock");
let layers: ReadonlyArray<SceneLayer> = SCENE_LAYERS;

if (lock) {
	let source = readSceneSource();
	const locked: SceneLayer[] = [];
	for (const layer of SCENE_LAYERS) {
		const art = await loadArt(layer.image);
		if (!art || layer.id === SCENE_BOARD_ID) {
			locked.push(layer);
			continue;
		}
		const height = round4(
			(layer.box.width * SCENE_ASPECT_RATIO * art.height) / art.width,
		);
		if (height !== layer.box.height) {
			console.log(
				`locked ${layer.id}: height ${layer.box.height} -> ${height}`,
			);
			source = setBoxHeight(source, layer.id, height);
		}
		locked.push({ ...layer, box: { ...layer.box, height } });
	}
	writeSceneSource(source);
	layers = locked;
}

for (const layer of layers) {
	const art = await loadArt(layer.image);
	if (!art) {
		continue;
	}
	const boxAspect = (layer.box.width / layer.box.height) * SCENE_ASPECT_RATIO;
	const artAspect = art.width / art.height;
	if (Math.abs(boxAspect / artAspect - 1) > ASPECT_TOLERANCE) {
		const height = round4(
			(layer.box.width * SCENE_ASPECT_RATIO) / artAspect,
		);
		failures.push(
			layer.id === SCENE_BOARD_ID
				? `board: trimmed art is ${art.width}x${art.height} but SCENE_BOARD_PIXELS is ${SCENE_BOARD_PIXELS.width}x${SCENE_BOARD_PIXELS.height}`
				: `${layer.id}: box aspect ${round4(boxAspect)} != art aspect ${round4(artAspect)}; height should be ${height} (run with --lock)`,
		);
	}
	if (
		layer.id === SCENE_BOARD_ID &&
		(art.width !== SCENE_BOARD_PIXELS.width ||
			art.height !== SCENE_BOARD_PIXELS.height)
	) {
		failures.push(
			`board: trimmed art is ${art.width}x${art.height}; update SCENE_BOARD_PIXELS (${SCENE_BOARD_PIXELS.width}x${SCENE_BOARD_PIXELS.height})`,
		);
	}
}

for (const tack of tackLayers(layers)) {
	const art = await loadArt(tack.image);
	if (!art) {
		continue;
	}
	const expected = SCENE_TACK_ASPECT[tack.variant];
	if (Math.abs(art.width / art.height / expected - 1) > ASPECT_TOLERANCE) {
		failures.push(
			`${tack.id}: tack art aspect ${round4(art.width / art.height)} != SCENE_TACK_ASPECT[${tack.variant}] ${expected}`,
		);
	}
}

if (failures.length > 0) {
	for (const failure of new Set(failures)) {
		console.error(`ERROR ${failure}`);
	}
	console.error("Nothing written.");
	process.exit(1);
}

// ---------------------------------------------------------------------------
// 2. One WebP per layer and per tack in use.
// ---------------------------------------------------------------------------

interface Result {
	id: string;
	trim: string;
	outputWidth: number;
	beforeBytes: number;
	afterBytes: number;
}

const results: Result[] = [];
const written = new Set<string>();

for (const layer of renderLayers(layers)) {
	const name = baseName(layer.image);
	const fileName = `${name}.webp`;
	if (written.has(fileName)) {
		continue; // two tacks sharing a colour and variant share a file
	}
	const art = await loadTrimmed(name);
	const targetWidth = Math.round(
		layer.box.width * SCENE_REFERENCE_WIDTH * DEVICE_PIXEL_RATIO,
	);
	const outputWidth = Math.min(targetWidth, art.width);
	const outputPath = `${outDir}${fileName}`;
	await sharpFrom(art)
		.resize({ width: outputWidth, withoutEnlargement: true })
		.webp({
			quality: layer.role === "board" ? BOARD_WEBP_QUALITY : WEBP_QUALITY,
			alphaQuality: WEBP_ALPHA_QUALITY,
			effort: WEBP_EFFORT,
		})
		.toFile(outputPath);
	written.add(fileName);
	results.push({
		id: name,
		trim: `${art.sourceWidth}x${art.sourceHeight} -> ${art.width}x${art.height}`,
		outputWidth,
		beforeBytes: art.sourceBytes,
		afterBytes: statSync(outputPath).size,
	});
}

// ---------------------------------------------------------------------------
// 3. The flat mobile scene: the same layers, composited. Sized like a layer
//    would be, and never larger than the board art it is built on.
// ---------------------------------------------------------------------------

const boardLayer = layers.find((layer) => layer.id === SCENE_BOARD_ID);
if (!boardLayer) {
	throw new Error(`SCENE_LAYERS has no "${SCENE_BOARD_ID}" layer`);
}
const board = await loadTrimmed(baseName(boardLayer.image));
const mobileWidth = Math.min(MOBILE_MAX_WIDTH * DEVICE_PIXEL_RATIO, board.width);
const mobileHeight = Math.round(mobileWidth / SCENE_ASPECT_RATIO);
const mobileName = `${baseName(SCENE_MOBILE_IMAGE)}.webp`;
const mobilePath = `${outDir}${mobileName}`;
const composed = await composeScene(
	layers,
	mobileWidth,
	mobileHeight,
	shadowAtWidth(SCENE_SHADOWS.rest, mobileWidth),
);
await composed
	.webp({
		quality: BOARD_WEBP_QUALITY,
		alphaQuality: WEBP_ALPHA_QUALITY,
		effort: WEBP_EFFORT,
	})
	.toFile(mobilePath);
written.add(mobileName);

// ---------------------------------------------------------------------------
// 4. The desktop board. At md and up the board is not one image but a frame
//    that fills the viewport: a 9-slice of the wood, cork tiled inside it,
//    and the art's inner shadow laid over the cork. All three are cut from
//    board.png here, and the measurements that place them — the slice
//    offsets above all — are written to a generated config module rather
//    than typed in.
// ---------------------------------------------------------------------------

const boardArt = await buildBoardArt(baseName(boardLayer.image), {
	frame: WEBP_QUALITY,
	cork: BOARD_WEBP_QUALITY,
	alpha: WEBP_ALPHA_QUALITY,
	effort: WEBP_EFFORT,
});
const boardFiles = [
	{ image: SCENE_BOARD_ART.frame, bytes: boardArt.files.frame },
	{ image: SCENE_BOARD_ART.cork, bytes: boardArt.files.cork },
	{ image: SCENE_BOARD_ART.shadow, bytes: boardArt.files.shadow },
];
for (const file of boardFiles) {
	const fileName = `${baseName(file.image)}.webp`;
	writeFileSync(`${outDir}${fileName}`, file.bytes);
	written.add(fileName);
}
const boardModulePath = fileURLToPath(
	new URL("../src/config/board-frame.gen.ts", import.meta.url),
);
const boardModule = boardFrameModule(boardArt.measure);
let boardModuleChanged = true;
try {
	boardModuleChanged = readFileSync(boardModulePath, "utf8") !== boardModule;
} catch {
	// First run: the module does not exist yet.
}
if (boardModuleChanged) {
	writeFileSync(boardModulePath, boardModule);
}

// ---------------------------------------------------------------------------
// 5. Drop outputs nothing refers to any more (an old scene's art, a tack
//    whose colour was reassigned).
// ---------------------------------------------------------------------------

const stale = readdirSync(outDir).filter(
	(file) => file.endsWith(".webp") && !written.has(file),
);
for (const file of stale) {
	unlinkSync(`${outDir}${file}`);
}

// ---------------------------------------------------------------------------
// Report.
// ---------------------------------------------------------------------------

const columns = [
	{ heading: "art", value: (r: Result) => r.id },
	{ heading: "trim", value: (r: Result) => r.trim },
	{ heading: "out px", value: (r: Result) => String(r.outputWidth) },
	{ heading: "before", value: (r: Result) => formatKilobytes(r.beforeBytes) },
	{ heading: "after", value: (r: Result) => formatKilobytes(r.afterBytes) },
];

const totalBefore = results.reduce((sum, r) => sum + r.beforeBytes, 0);
const totalAfter = results.reduce((sum, r) => sum + r.afterBytes, 0);
const rows = results.map((result) =>
	columns.map((column) => column.value(result)),
);
const total = [
	"TOTAL (layers)",
	"",
	"",
	formatKilobytes(totalBefore),
	formatKilobytes(totalAfter),
];

const widths = columns.map((column, index) =>
	Math.max(
		column.heading.length,
		...[...rows, total].map((row) => row[index].length),
	),
);
const line = (cells: string[]) =>
	cells
		.map((cell, index) => cell.padEnd(widths[index]))
		.join("  ")
		.trimEnd();
const rule = widths.map((width) => "-".repeat(width)).join("  ");

console.log(line(columns.map((column) => column.heading)));
console.log(rule);
for (const row of rows) {
	console.log(line(row));
}
console.log(rule);
console.log(line(total));
console.log(
	`\nmobile composite: ${mobileName} ${mobileWidth}x${mobileHeight}, ${formatKilobytes(statSync(mobilePath).size)}`,
);
const { slice, tile, shadow } = boardArt.measure;
console.log(
	`\ndesktop board, measured from ${baseName(boardLayer.image)}.png (art px):`,
);
console.log(
	`  frame slices   top ${slice.top}  right ${slice.right}  bottom ${slice.bottom}  left ${slice.left}`,
);
console.log(`  cork tile      ${tile.width}x${tile.height} (a ${tile.width / 2}px patch, mirrored 2x2)`);
console.log(
	`  inner shadow   ${shadow.width}x${shadow.height} overlay, slices top ${shadow.slice.top}  left ${shadow.slice.left}`,
);
for (const file of boardFiles) {
	console.log(
		`  ${`${baseName(file.image)}.webp`.padEnd(20)} ${formatKilobytes(file.bytes.length)}`,
	);
}
console.log(
	`  src/config/board-frame.gen.ts ${boardModuleChanged ? "rewritten" : "unchanged"}`,
);
for (const file of stale) {
	console.log(`removed stale output: ${file}`);
}
